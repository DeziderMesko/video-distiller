#!/usr/bin/env python3
"""Write INDEX.md into the data directory: a table of everything distilled,
linking to each summary."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

# Run with any Python, not just the venv's: the two modules used here are
# dependency-free, so the project root on sys.path is all they need.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from vdistill.config import DATA_DIR as DATA  # noqa: E402
from vdistill.timecode import duration  # noqa: E402


def main() -> int:
    rows, total = [], 0
    for meta_path in sorted(DATA.glob("*/meta.json")):
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        directory = meta_path.parent
        total += meta.get("duration_seconds") or 0
        title = re.split(r"\s+#", meta.get("title", directory.name))[0].strip()
        links = []
        if (directory / "summary.md").exists():
            links.append(f"[summary]({directory.name}/summary.md)")
        if (directory / "transcript.timed.txt").exists():
            links.append(f"[timed]({directory.name}/transcript.timed.txt)")
        elif (directory / "transcript.txt").exists():
            links.append(f"[text]({directory.name}/transcript.txt)")
        answers = sorted((directory / "answers").glob("*.md"))
        if answers:
            links.append(f"{len(answers)} Q&A")
        rows.append((
            meta.get("uploader") or "?", title,
            duration(meta.get("duration_seconds")),
            (meta.get("language") or "?"),
            " · ".join(links),
            meta.get("source_url", ""),
        ))

    rows.sort(key=lambda r: (r[0], r[1]))
    out = [
        "# Index\n",
        f"{len(rows)} videos, {duration(total)} of audio. Generated by "
        "`scripts/build_index.py` — re-run it after distilling anything new.\n",
        "| Channel | Video | Length | Lang | Files | Source |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for uploader, title, length, lang, links, url in rows:
        out.append(
            f"| {uploader[:28]} | {title[:58]} | {length} | {lang} | {links} "
            f"| [watch]({url}) |"
        )
    (DATA / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{DATA / 'INDEX.md'}: {len(rows)} videos, {duration(total)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
